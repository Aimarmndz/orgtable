import { describe, it, expect } from "vitest";
import { generateKeyBetween } from "fractional-indexing";
import { positionAtEnd, isValidPositionKey } from "@/app/lib/ordering";

// The order of lists/cards is a lexicographic string key (fractional indexing, ADR 0002).
// What matters: appending at the end keeps the order, and keys coming from the client are
// validated before being stored.
describe("ordering (fractional indexing)", () => {
  it("positionAtEnd produces keys in lexicographic order when appending at the end", () => {
    let last: string | null = null;
    const keys: string[] = [];
    for (let i = 0; i < 6; i++) {
      const k = positionAtEnd(last);
      keys.push(k);
      last = k;
    }
    expect(keys).toEqual([...keys].sort());
    // No repeated keys.
    expect(new Set(keys).size).toBe(keys.length);
  });

  it("isValidPositionKey accepts keys generated by the library", () => {
    expect(isValidPositionKey("a0")).toBe(true);
    expect(isValidPositionKey("a0V")).toBe(true);
    expect(isValidPositionKey(positionAtEnd(positionAtEnd(null)))).toBe(true);
  });

  // Regression: with a 64-character cap, always dropping cards into the same gap exceeded
  // the cap after 373 insertions and moveCard/reorderList returned ok:false.
  it("isValidPositionKey accepts the long keys produced by inserting into the same gap", () => {
    const first = generateKeyBetween(null, null);
    let next = generateKeyBetween(first, null);
    for (let i = 0; i < 1000; i++) {
      next = generateKeyBetween(first, next);
    }
    expect(next.length).toBeGreaterThan(64);
    expect(isValidPositionKey(next)).toBe(true);
  });

  it("isValidPositionKey rejects keys that would break positionAtEnd", () => {
    const bad = ["", "x", "a", "a00", "!!!", "a0 ", "zzzz~", "a" + "1".repeat(1024)];
    for (const key of bad) {
      expect(isValidPositionKey(key)).toBe(false);
    }
  });
});
