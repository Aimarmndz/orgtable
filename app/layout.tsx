import type { Metadata } from "next";
import { getI18n } from "@/app/i18n/server";
import { I18nProvider } from "@/app/i18n/client";
import { headers } from "next/headers";
import { Bricolage_Grotesque, Figtree, Geist_Mono } from "next/font/google";
import "./globals.css";

// Every font is OFL (Google Fonts). next/font downloads them at build time and serves them
// from the app itself: nothing is requested from a CDN at runtime. The previous ones
// (Satoshi and Cabinet Grotesk, from Fontshare) forbid redistributing the files in a public
// repository, which is incompatible with publishing the code under the AGPL. See DESIGN.md.

// Figtree: sans-serif for the interface and body text.
const figtree = Figtree({
  variable: "--font-figtree",
  subsets: ["latin", "latin-ext"],
  display: "swap",
});

// Bricolage Grotesque: display face for headings and the brand, with editorial character.
const bricolage = Bricolage_Grotesque({
  variable: "--font-bricolage",
  subsets: ["latin", "latin-ext"],
  display: "swap",
});

// Geist Mono: only for tabular numbers, metadata and technical details.
const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Each page exports its own `title` and the template appends the app name, so every route
// has a distinct title (WCAG 2.4.2). The description follows the visitor's language.
export async function generateMetadata(): Promise<Metadata> {
  const { m, intl } = await getI18n();
  return {
    title: { template: "%s · orgtable", default: "orgtable" },
    description: m.common.tagline,
    applicationName: "orgtable",
    openGraph: {
      type: "website",
      siteName: "orgtable",
      title: "orgtable",
      description: m.common.tagline,
      locale: intl.replace("-", "_"),
    },
  };
}

// Runs before the first paint to apply the saved theme (or the system preference) without
// a flash. It must be inline in <head>.
const themeScript = `(function(){try{var t=localStorage.getItem('theme');var m=window.matchMedia('(prefers-color-scheme: dark)').matches;if(t==='dark'||(t!=='light'&&m)){document.documentElement.classList.add('dark')}}catch(e){}})();`;

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // CSP nonce (generated by proxy.ts). The theme script is inline and the CSP would block
  // it without the nonce: the page would flash light before switching to dark.
  const nonce = (await headers()).get("x-nonce") ?? undefined;
  const { locale, intl, m } = await getI18n();
  return (
    <html
      lang={locale}
      suppressHydrationWarning
      className={`${figtree.variable} ${bricolage.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script nonce={nonce} dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className="flex min-h-full flex-col bg-bg text-ink">
        <I18nProvider locale={locale} intl={intl} messages={m}>
          {children}
        </I18nProvider>
      </body>
    </html>
  );
}
