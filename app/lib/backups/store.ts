import "server-only";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { decryptBytes, decryptSecret, encryptBytes } from "@/app/lib/crypto/secrets";
import { s3Delete, s3Get, s3Put, type S3Target } from "@/app/lib/backups/s3";

// Where backup files go (docs/backups.md, "Destinations"): a directory on this server
// (ORGTABLE_BACKUP_DIR; a volume of its own in docker-compose) or the organization's own S3
// bucket. A file may be encrypted before it leaves this process: AES-256-GCM bound to the
// backup's id, so only an instance with the same ORGTABLE_SECRET_KEY can open it.

// `turbopackIgnore`: see app/lib/storage.ts.
export function backupDir(): string {
  return process.env.ORGTABLE_BACKUP_DIR || path.join(/* turbopackIgnore: true */ process.cwd(), "backups", "app");
}

export const backupContext = (backupId: string) => `backup:${backupId}`;

export type DestinationConfig = {
  destination: "LOCAL" | "S3";
  s3Endpoint: string | null;
  s3Region: string | null;
  s3Bucket: string | null;
  s3Prefix: string | null;
  s3AccessKeyEnc: string | null;
  s3SecretKeyEnc: string | null;
};

export const s3SecretContext = (configId: string, field: "access" | "secret") => `backup-s3:${configId}:${field}`;

export function s3TargetOf(configId: string, c: DestinationConfig): S3Target {
  if (!c.s3Endpoint || !c.s3Bucket || !c.s3AccessKeyEnc || !c.s3SecretKeyEnc) {
    throw new Error("The S3 destination is not complete");
  }
  return {
    endpoint: c.s3Endpoint,
    region: c.s3Region || "us-east-1",
    bucket: c.s3Bucket,
    accessKey: decryptSecret(c.s3AccessKeyEnc, s3SecretContext(configId, "access")),
    secretKey: decryptSecret(c.s3SecretKeyEnc, s3SecretContext(configId, "secret")),
  };
}

/** "folder/" with exactly one trailing slash (or "" for the bucket's root). */
export function cleanPrefix(prefix: string | null): string {
  const p = (prefix ?? "").trim().replace(/^\/+|\/+$/g, "");
  return p ? `${p}/` : "";
}

function localPath(location: string): string {
  // Locations are generated by orgtable ("<scope>/<file>"); normalize keeps them inside.
  const clean = path.normalize(location).replace(/^(\.\.(\/|\\|$))+/, "");
  return path.join(backupDir(), clean);
}

/** Stores a backup file and returns where it went. */
export async function storeBackupFile(input: {
  backupId: string;
  scope: string;
  bytes: Buffer;
  encrypt: boolean;
  configId: string;
  config: DestinationConfig;
}): Promise<{ location: string; size: number }> {
  const name = `${new Date().toISOString().replace(/[:.]/g, "-")}-${input.backupId}.zip${input.encrypt ? ".enc" : ""}`;
  const body = input.encrypt ? Buffer.from(encryptBytes(input.bytes, backupContext(input.backupId)), "utf8") : input.bytes;
  if (input.config.destination === "S3") {
    const location = `${cleanPrefix(input.config.s3Prefix)}${input.scope}/${name}`;
    await s3Put(s3TargetOf(input.configId, input.config), location, body);
    return { location, size: body.length };
  }
  const location = `${input.scope}/${name}`;
  await mkdir(path.dirname(localPath(location)), { recursive: true });
  await writeFile(localPath(location), body);
  return { location, size: body.length };
}

/** Reads a stored backup back, decrypted: the plain .zip. */
export async function loadBackupFile(input: {
  backupId: string;
  location: string;
  destination: "LOCAL" | "S3";
  encrypted: boolean;
  configId: string;
  config: DestinationConfig | null;
}): Promise<Buffer> {
  const raw =
    input.destination === "S3"
      ? await s3Get(s3TargetOf(input.configId, input.config!), input.location)
      : await readFile(localPath(input.location));
  return input.encrypted ? decryptBytes(raw.toString("utf8"), backupContext(input.backupId)) : raw;
}

/** Deletes a stored file; never throws (a missing file is fine, anything else is logged). */
export async function deleteBackupFile(input: {
  location: string;
  destination: "LOCAL" | "S3";
  configId: string;
  config: DestinationConfig | null;
}): Promise<void> {
  try {
    if (input.destination === "S3") await s3Delete(s3TargetOf(input.configId, input.config!), input.location);
    else await unlink(localPath(input.location));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return;
    console.error("[backups] could not delete a backup file", { location: input.location, error: String(error).slice(0, 200) });
  }
}
